#!/usr/bin/env node
import { readFile, writeFile, mkdir } from 'node:fs/promises';

function Usage() { console.log('Usage: generate-platforms.mjs [-h|--help]'); }
const args = process.argv.slice(2);
if (args.includes('-h') || args.includes('--help')) { Usage(); process.exit(0); }
if (args.length) { Usage(); process.exit(2); }
const base = new URL('../', import.meta.url);
const read = async (path) => JSON.parse(await readFile(new URL(path, base), 'utf8'));
const palette = await read('src/phosphor/build/tokens.generated.json');
const motion = await read('src/motion.tokens.json');
const durations = {};
const easings = {};
const declarations = [];
for (const [name, token] of Object.entries(motion)) {
  if (token.$type === 'duration') {
    const { value, unit } = token.$value;
    if (!Number.isFinite(value) || value < 0 || !['ms', 's'].includes(unit)) throw new Error(`Invalid duration: ${name}`);
    durations[name] = unit === 'ms' ? value / 1000 : value;
    declarations.push(`  --${name === 'duration' ? name : `${name}-duration`}: ${value}${unit};`);
  } else if (token.$type === 'cubicBezier') {
    const values = token.$value;
    if (values.length !== 4 || !values.every(Number.isFinite) || [values[0], values[2]].some(v => v < 0 || v > 1)) throw new Error(`Invalid easing: ${name}`);
    easings[name] = values;
    declarations.push(`  --${name}: cubic-bezier(${values.join(', ')});`);
  } else throw new Error(`Unsupported motion token: ${name}`);
}
await writeFile(new URL('src/phosphor/motion.css', base), `/* Generated from motion.tokens.json. */\n:root {\n${declarations.join('\n')}\n}\n`);
await writeFile(new URL('src/motion.ts', base), `// Generated from motion.tokens.json.\nexport const durations = ${JSON.stringify(durations, null, 2)} as const;\nexport const easings = ${JSON.stringify(easings, null, 2)} as const;\n`);

function rgba(value) {
  if (/^#[\da-f]{6}$/i.test(value)) return [...[1, 3, 5].map(i => parseInt(value.slice(i, i + 2), 16) / 255), 1];
  const match = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (!match) throw new Error(`Unsupported color: ${value}`);
  return [Number(match[1]) / 255, Number(match[2]) / 255, Number(match[3]) / 255, Number(match[4])];
}
const dimensions = Object.fromEntries([...palette.spacing.tokens, ...palette.radius.tokens].map(token => {
  if (!/^\d+(\.\d+)?px$/.test(token.value)) throw new Error(`Unsupported dimension: ${token.name}`);
  return [token.name, parseFloat(token.value)];
}));
const swiftMap = (values) => Object.entries(values).map(([key, value]) => `        "${key}": ${value}`).join(',\n');
const colorMaps = ['light', 'dark'].map(mode => `        "${mode}": [\n${palette.color.tokens.map(token => {
  const [red, green, blue, alpha] = rgba(token.value[mode]);
  return `            "${token.name}": AbmexRGBA(red: ${red}, green: ${green}, blue: ${blue}, alpha: ${alpha})`;
}).join(',\n')}\n        ]`).join(',\n');
const destination = new URL('../../Sources/AbmexTokens/', base);
await mkdir(destination, { recursive: true });
await writeFile(new URL('AbmexMotion.swift', destination), `// Generated from motion.tokens.json. Do not edit.\npublic extension AbmexTokens {\n    static let easings: [String: [Double]] = [\n${swiftMap(Object.fromEntries(Object.entries(easings).map(([name, values]) => [name, `[${values.join(', ')}]`])))}\n    ]\n}\n`);
await writeFile(new URL('AbmexTokens.swift', destination), `// Generated by packages/themes/scripts/generate-platforms.mjs. Do not edit.\npublic struct AbmexRGBA: Equatable, Sendable {\n    public let red: Double\n    public let green: Double\n    public let blue: Double\n    public let alpha: Double\n    public init(red: Double, green: Double, blue: Double, alpha: Double = 1) {\n        self.red = red; self.green = green; self.blue = blue; self.alpha = alpha\n    }\n}\n\npublic enum AbmexTokens {\n    public static let colors: [String: [String: AbmexRGBA]] = [\n${colorMaps}\n    ]\n    public static let durations: [String: Double] = [\n${swiftMap(durations)}\n    ]\n    public static let dimensions: [String: Double] = [\n${swiftMap(dimensions)}\n    ]\n}\n`);
